'''
The main() function - parse arguments, create directory, call other functions
'''
def main():
    global assembly_source_name_32
    global assembly_object_name_32
    global assembly_source_name_64
    global assembly_object_name_64
    parser = argparse.ArgumentParser()
    parser.add_argument("stem", help="Name of program. Source and header will be named this.")
    parser.add_argument( "-a", "--create_asm32", help="Add a 32-bit x86 assembly source file (requires NASM to build)", action="store_true")
    parser.add_argument( "-A", "--create_asm64", help="Add a 64-bit x86 assembly source file (requires NASM to build)", action="store_true")
    parser.add_argument( "-d", "--create_header", help="Add a header file", action="store_true")
    parser.add_argument( "-f", "--create_filemap", help="Add code to open the first argument as a mapped file (requires -u also)", action="store_true")
    parser.add_argument( "-m", "--create_makefile", help="Add a makefile", action="store_true")
    parser.add_argument( "-u", "--create_utility_functions", help="Add a file containing utility functions", action="store_true")

    args = parser.parse_args()

    has_asm32 = False
    has_asm64 = False
    has_makefile = False
    # get the current directory - we will make our directory here
    current_directory = getcwd()
    stem = args.stem


    file_list = []
    path = current_directory + '/' + stem
    mkdir(path) 
    c_source_path_filename = "%s/%s.c" % ( path, stem )
    file_list.append( "%s.c" % stem )
    c_header_path_filename = ""
    makefile_path_filename = ""

    # assume if we're creating utility functions then we also want a makefile
    if args.create_utility_functions:
        utility_header_path_filename = "%s/%s.h" % ( path, UTILITY_HEADER )
        utility_code_path_filename   = "%s/%s.c" % ( path, UTILITY_SOURCE )
        file_list.append( "%s.c" % UTILITY_SOURCE )

        if( make_utility_header( stem, utility_header_path_filename ) == False ):
            print( "Error creating utility header file" )
            exit(-1)
        
        if( make_utility_code( stem, utility_code_path_filename ) == False ):
            print( "Error creating utility source code file" )
            exit(-1)
        has_makefile = True

    if args.create_header:
        c_header_path_filename = "%s/%s.h" % ( path, stem )

    # only necessary if a bare C file is being created    
    if args.create_makefile:
        has_makefile = True
        

    # assume if we're creating assembly source then we need a makefile 
    if args.create_asm32:
        assembly_source_name_32 = ASM32_SOURCE_SUFFIX % stem
        assembly_object_name_32 = ASM32_OBJECT_SUFFIX % stem
        if( make_asm32_file( stem, "%s/%s" % ( path, assembly_source_name_32 ) ) == False ):
            print( "Error creating 32-bit assembly source file" )
            exit(-1)
        has_asm32 = True
        has_makefile = True

    elif args.create_asm64:
        assembly_source_name_64 = ASM64_SOURCE_SUFFIX % stem
        assembly_object_name_64 = ASM64_OBJECT_SUFFIX % stem
        if( make_asm64_file( stem, "%s/%s" % ( path, assembly_source_name_64 ) ) == False ):
            print( "Error creating 64-bit assembly source file" )
            exit(-1)
        has_asm64 = True
        has_makefile = True

    if( make_c_file( stem, c_source_path_filename, args.create_header, args.create_utility_functions, args.create_filemap, has_asm32, has_asm64 ) == False ):
        print( "Error creating C source file" )
        exit(-1)

    if( args.create_header ):
        if( make_c_header( stem, c_header_path_filename ) == False ):
            print( "Error creating header file" )
            exit(-1)

    if( has_makefile == True ):
        makefile_path_filename = "%s/Makefile" % path
        if( make_makefile( stem, makefile_path_filename, file_list, has_asm32, has_asm64 ) == False ):
            print( "Error creating Makefile" )
            exit(-1)

    print( "[Ok]" ) 


if __name__ == "__main__":
    main()