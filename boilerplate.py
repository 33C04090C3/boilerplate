def make_c_file(filestem, path_and_filename, include_header=False, include_utility=False, make_mapping=False, has_asm32=False, has_asm64=False):
    
    # assemble the file contents
    result =  make_comment_block(filestem)
    result += make_includes()
    if( include_header == True ):
        result += "#include \"%s.h\"\n" % filestem
    if( include_utility == True ):
        result += "#include \"%s.h\"\n" % UTILITY_HEADER
    result += "\n\n"

    # add asm function prototypes if necessary
    if( has_asm32 == True ):
        result += assembly_prototype_32 % ASM_FUNC32_NAME
        result += "\n\n"
    elif( has_asm64 == True ):
        result += assembly_prototype_64 % ASM_FUNC32_NAME
        result += "\n\n"

    if( include_utility == True and make_mapping == True ):
        result += make_main_function_with_file_map(filestem, has_asm32, has_asm64)
    else:
        result += make_main_function(filestem, has_asm32, has_asm64)

    # write it to the file
    try:
        with open( path_and_filename, "w+" ) as fh:
            fh.write(result)
    except Exception as e:
        print( "Error: %s\n" % e )
        return False

    return True

