        result += "nasm -felf32 -o %s %s\n\t" % ( assembly_object_name_32, assembly_source_name_32 )
        files.append( assembly_object_name_32 )
        extra_options += "-m32" # assume we're on a 64-bit system and need to tell gcc it should build the entire program as 32-bit
